"""Pure PERF-01 helpers: statistics, plan parsing, and report rendering. No database access."""

from __future__ import annotations

import math
import re
from statistics import fmean
from typing import Any

SEED_VERSION = "perf-cse321-v1"
MIN_SAMPLES_FOR_P95 = 20


def percentile(samples: list[float], pct: float) -> float:
    """Nearest-rank percentile (no interpolation), so reported values are real observations."""
    if not samples:
        raise ValueError("No samples.")
    if not 0 < pct <= 100:
        raise ValueError("pct must be in (0, 100].")
    ordered = sorted(samples)
    return ordered[math.ceil(pct / 100 * len(ordered)) - 1]


def summarize(samples: list[float]) -> dict[str, Any]:
    return {
        "n": len(samples),
        "min": round(min(samples), 2),
        "p50": round(percentile(samples, 50), 2),
        "p95": round(percentile(samples, 95), 2),
        "max": round(max(samples), 2),
        "mean": round(fmean(samples), 2),
        "p95_reliable": len(samples) >= MIN_SAMPLES_FOR_P95,
    }


_PLANNING = re.compile(r"Planning Time: ([0-9.]+) ms")
_EXECUTION = re.compile(r"Execution Time: ([0-9.]+) ms")
_SEQ_SCAN = re.compile(r"Seq Scan on (\S+)")
_BUFFERS = re.compile(r"Buffers: shared(?: hit=(\d+))?(?: read=(\d+))?")


def parse_plan(text: str) -> dict[str, Any]:
    """Extract headline numbers from `EXPLAIN (ANALYZE, BUFFERS)` text output."""
    planning = _PLANNING.search(text)
    execution = _EXECUTION.search(text)
    buffers = _BUFFERS.search(text)  # first match is the root node (includes children)
    return {
        "planning_ms": float(planning.group(1)) if planning else None,
        "execution_ms": float(execution.group(1)) if execution else None,
        "seq_scans": sorted(set(_SEQ_SCAN.findall(text))),
        "shared_hit": int(buffers.group(1) or 0) if buffers else None,
        "shared_read": int(buffers.group(2) or 0) if buffers else None,
    }


def fmt_bytes(value: float | None) -> str:
    if value is None:
        return "-"
    size = float(value)
    for unit in ("B", "KiB", "MiB", "GiB"):
        if size < 1024 or unit == "GiB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024
    return f"{size:.1f} GiB"


def verdict(p95_ms: float | None, target_ms: float | None) -> str:
    if target_ms is None:
        return "no target recorded"
    if p95_ms is None:
        return "not measured"
    return "PASS" if p95_ms <= target_ms else f"MISS (target {target_ms:g} ms)"


def render_markdown(results: dict[str, Any], targets: dict[str, Any]) -> str:
    """Render raw results as the generated section of the CSE321 report."""
    meta = results["meta"]
    out: list[str] = ["# CSE321 performance results (generated)", ""]
    out.append("> Generated by `perf_measure`. Do not edit by hand; edit the report instead.")
    out += ["", "## Environment", "", "| Item | Value |", "|---|---|"]
    for key, value in meta.items():
        if key != "pg_settings":
            out.append(f"| {key} | {value} |")
    for name, value in (meta.get("pg_settings") or {}).items():
        out.append(f"| pg:{name} | {value} |")

    for label, key in (("After seed", "tables_before"), ("After benchmark", "tables_after")):
        out += ["", f"## Row counts and storage ({label})", ""]
        out.append("| Table | Rows (exact) | Heap | TOAST | Indexes | Total |")
        out.append("|---|---:|---:|---:|---:|---:|")
        for t in results.get(key, []):
            out.append(
                f"| {t['table']} | {t['rows']:,} | {fmt_bytes(t['heap_bytes'])} | "
                f"{fmt_bytes(t['toast_bytes'])} | {fmt_bytes(t['index_bytes'])} | "
                f"{fmt_bytes(t['total_bytes'])} |"
            )

    out += ["", "## Latency (ms)", ""]
    out.append(
        "| Query | State | Filters | Conc. | n | first | p50 | p95 | max | queries | vs target |"
    )
    out.append("|---|---|---|---:|---:|---:|---:|---:|---:|---:|---|")
    for row in results.get("latency", []):
        if "error" in row:
            out.append(
                f"| {row['name']} | {row['state']} | {row['filters']} | - | - | - | - | - | - | - | ERROR: {row['error']} |"
            )
            continue
        target = (targets.get(row["name"]) or {}).get("p95_ms")
        note = "" if row.get("p95_reliable") else " (n<20: p95 unreliable)"
        out.append(
            f"| {row['name']} | {row['state']} | {row['filters']} | {row['concurrency']} | "
            f"{row['n']} | {row.get('first_ms', '-')} | {row['p50']} | {row['p95']} | {row['max']} | "
            f"{row.get('queries', '-')} | {verdict(row['p95'], target)}{note} |"
        )

    if results.get("scoring"):
        s = results["scoring"]
        out += ["", "## Scoring (with evidence persistence)", ""]
        for key, value in s.items():
            out.append(f"- **{key}**: {value}")
    if results.get("import"):
        out += ["", "## CSV import throughput", ""]
        for key, value in results["import"].items():
            out.append(f"- **{key}**: {value}")
    if results.get("contention"):
        out += ["", "## Concurrency, lock waits and connections", ""]
        for key, value in results["contention"].items():
            out.append(f"- **{key}**: {value}")
    if results.get("payload"):
        out += ["", "## Evidence and manifest payload", ""]
        for key, value in results["payload"].items():
            out.append(f"- **{key}**: {value}")

    out += ["", "## Query plans (`EXPLAIN (ANALYZE, BUFFERS)`)", ""]
    for plan in results.get("plans", []):
        out.append(f"### {plan['name']} ({plan['state']})")
        if "error" in plan:
            out += ["", f"Not captured: {plan['error']}", ""]
            continue
        out.append(
            f"planning {plan['planning_ms']} ms, execution {plan['execution_ms']} ms, "
            f"buffers hit={plan['shared_hit']} read={plan['shared_read']}, "
            f"seq scans: {', '.join(plan['seq_scans']) or 'none'}"
        )
        out += ["", "```text", plan["text"].rstrip(), "```", ""]
    return "\n".join(out) + "\n"
